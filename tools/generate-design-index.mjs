import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LIFECYCLE = ['draft', 'accepted', 'implementing', 'blocked', 'reopened', 'verified', 'superseded'];

function exactlyOne(matches, label) {
  if (matches.length !== 1) throw new Error(`design_index_${label}: expected exactly one match, found ${matches.length}`);
  return matches[0];
}

export function parseDesignRecord(text, relativePath = '') {
  const title = exactlyOne([...text.matchAll(/^# Design (\d{4})\s*(?::|—|-)\s*(.+)$/gm)], 'title');
  const statusLine = exactlyOne([...text.matchAll(/^- Status:\s*(.+)$/gm)], 'status')[1].replaceAll('`', '').trim();
  const status = LIFECYCLE.find((candidate) => new RegExp(`^${candidate}\\b`).test(statusLine));
  if (!status) throw new Error(`design_index_status: unsupported lifecycle in ${relativePath || title[1]}: ${statusLine}`);
  const revisions = [...text.matchAll(/^- Revision:\s*(\d+)\s*$/gm)];
  if (revisions.length > 1) throw new Error(`design_index_revision: expected at most one revision in ${relativePath || title[1]}`);
  return {
    id: `D${title[1]}`,
    numericId: title[1],
    title: title[2].trim(),
    status,
    revision: revisions.length === 1 ? Number(revisions[0][1]) : 1,
    explicitRevision: revisions.length === 1,
    relativePath,
  };
}

export function collectDesignRecords(root = process.cwd(), { readText } = {}) {
  const designDir = path.join(root, 'docs/design');
  const names = fs.readdirSync(designDir).filter((name) => /^\d{4}-[a-z0-9-]+\.md$/.test(name)).sort();
  const records = names.map((name) => {
    const relativePath = `docs/design/${name}`;
    const text = readText ? readText(relativePath) : fs.readFileSync(path.join(root, relativePath), 'utf8');
    const record = parseDesignRecord(text, relativePath);
    if (record.numericId !== name.slice(0, 4)) throw new Error(`design_index_filename_id_mismatch: ${relativePath}`);
    return record;
  });
  const seen = new Set();
  for (const record of records) {
    if (seen.has(record.id)) throw new Error(`design_index_duplicate_id: ${record.id}`);
    seen.add(record.id);
  }
  return records;
}

export function renderDesignIndex(root = process.cwd(), options = {}) {
  const records = collectDesignRecords(root, options);
  const lines = [
    '# design registry',
    '',
    '> Deterministic projection generated by `node tools/generate-design-index.mjs`. Maintained Design files own title, lifecycle status and revision. This file is derived and must never authorize implementation or override a Design owner.',
    '',
    '| ID | Revision | Status | Title | File |',
    '| --- | --- | --- | --- | --- |',
    ...records.map((record) => `| ${record.id} | r${record.revision} | ${record.status} | ${record.title.replaceAll('|', '\\|')} | \`${record.relativePath}\` |`),
    '',
    'Records without an explicit `Revision` field are rendered as legacy `r1` under `SDD.md`.',
    '',
  ];
  return lines.join('\n');
}

function runCli() {
  const root = process.cwd();
  const target = path.join(root, 'docs/design/README.md');
  const expected = renderDesignIndex(root);
  if (process.argv.includes('--check')) {
    const actual = fs.readFileSync(target, 'utf8');
    if (actual !== expected) {
      process.stderr.write('design_index_drift\n');
      process.exitCode = 1;
      return;
    }
    process.stdout.write('design-index ok\n');
    return;
  }
  fs.writeFileSync(target, expected);
  process.stdout.write(`design-index wrote ${collectDesignRecords(root).length} records\n`);
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : null;
if (invokedPath && invokedPath === path.resolve(fileURLToPath(import.meta.url))) runCli();
